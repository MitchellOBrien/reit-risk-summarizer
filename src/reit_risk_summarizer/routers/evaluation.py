"""Evaluation and quality metrics endpoints.

This router exposes the evaluation system's results via REST API for production monitoring
and observability. It provides programmatic access to LLM quality metrics, enabling:

- Real-time quality monitoring dashboards
- CI/CD integration for automated quality gates
- Historical performance tracking
- Per-ticker metric analysis

The evaluation system compares LLM-generated risk summaries against expert-curated golden
datasets using three metrics:
1. Semantic Similarity (0-1): How semantically similar LLM risks are to expert risks
2. NDCG@5 (0-1): Ranking quality - are most important risks ranked highest?
3. Sector-Specificity (0-1): How sector-specific (vs generic) the risks are

Endpoints:
- GET /evaluation/results: Full evaluation report with aggregate metrics
- GET /evaluation/metrics/{ticker}: Per-ticker detailed metrics
- GET /evaluation/health: System health check (results availability, cache status)

Evaluation results are generated by running: python -m evaluation.run_evaluation
Results are cached in: evaluation/results/evaluation_results.json
"""

import json
import logging
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel, Field

from ..config import Settings, get_settings

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/evaluation", tags=["evaluation"])


class EvaluationMetrics(BaseModel):
    """Evaluation metrics for a single ticker."""
    
    ticker: str
    company_name: str
    sector: str
    semantic_similarity: float = Field(ge=0, le=1, description="Cosine similarity between LLM and expert risks")
    ndcg_at_5: float = Field(ge=0, le=1, description="Normalized Discounted Cumulative Gain at rank 5")
    sector_specificity: float = Field(ge=0, le=1, description="How sector-specific the risks are")
    source: str = Field(description="cached_golden_output or groq_api")


class EvaluationSummary(BaseModel):
    """Summary of evaluation results."""
    
    run_date: str
    total_tickers: int
    cached_only_mode: bool
    tickers_evaluated: int
    mean_similarity: float
    mean_ndcg: float
    mean_specificity: float
    tickers_meeting_targets: int


class EvaluationResults(BaseModel):
    """Complete evaluation results."""
    
    summary: EvaluationSummary
    tickers: list[EvaluationMetrics]


@router.get("/results", response_model=EvaluationResults)
async def get_evaluation_results() -> EvaluationResults:
    """
    Get the latest evaluation results.
    
    Returns metrics comparing LLM-generated risks against expert-curated golden dataset.
    
    Raises:
        HTTPException: If evaluation results file not found.
    """
    results_path = Path(__file__).parent.parent.parent.parent / "evaluation" / "results" / "evaluation_results.json"
    
    if not results_path.exists():
        raise HTTPException(
            status_code=404,
            detail="Evaluation results not found. Run: python -m evaluation.run_evaluation --cached-only"
        )
    
    try:
        with open(results_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        # Extract summary metrics
        metadata = data["metadata"]
        summary_metrics = data.get("summary_metrics", {})
        
        # Count tickers meeting targets
        targets = {"semantic_similarity": 0.75, "ndcg_at_5": 0.70, "sector_specificity": 0.40}
        tickers_meeting_targets = sum(
            1 for t in data["tickers"] 
            if t.get("metrics") and all(
                t["metrics"][key] >= threshold 
                for key, threshold in targets.items()
            )
        )
        
        summary = EvaluationSummary(
            run_date=metadata["run_date"],
            total_tickers=metadata["total_tickers"],
            cached_only_mode=metadata.get("cached_only_mode", False),
            tickers_evaluated=len(data["tickers"]),
            mean_similarity=summary_metrics.get("semantic_similarity", {}).get("mean", 0.0),
            mean_ndcg=summary_metrics.get("ndcg_at_5", {}).get("mean", 0.0),
            mean_specificity=summary_metrics.get("sector_specificity", {}).get("mean", 0.0),
            tickers_meeting_targets=tickers_meeting_targets
        )
        
        # Extract ticker metrics
        tickers = [
            EvaluationMetrics(
                ticker=t["ticker"],
                company_name=t["company_name"],
                sector=t["sector"],
                semantic_similarity=t["metrics"]["semantic_similarity"],
                ndcg_at_5=t["metrics"]["ndcg_at_5"],
                sector_specificity=t["metrics"]["sector_specificity"],
                source=t["source"]
            )
            for t in data["tickers"]
            if t.get("metrics")
        ]
        
        return EvaluationResults(summary=summary, tickers=tickers)
        
    except (KeyError, json.JSONDecodeError) as e:
        logger.error(f"Failed to parse evaluation results: {e}")
        raise HTTPException(
            status_code=500,
            detail=f"Invalid evaluation results format: {str(e)}"
        )


@router.get("/metrics/{ticker}", response_model=EvaluationMetrics)
async def get_ticker_metrics(ticker: str) -> EvaluationMetrics:
    """
    Get evaluation metrics for a specific ticker.
    
    Args:
        ticker: Stock ticker symbol (e.g., AMT, PLD, EQIX)
        
    Raises:
        HTTPException: If results not found or ticker not in results.
    """
    results_path = Path(__file__).parent.parent.parent.parent / "evaluation" / "results" / "evaluation_results.json"
    
    if not results_path.exists():
        raise HTTPException(
            status_code=404,
            detail="Evaluation results not found"
        )
    
    try:
        with open(results_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        # Find ticker in results
        ticker_data = next(
            (t for t in data["tickers"] if t["ticker"].upper() == ticker.upper()),
            None
        )
        
        if not ticker_data or not ticker_data.get("metrics"):
            raise HTTPException(
                status_code=404,
                detail=f"Ticker {ticker} not found in evaluation results"
            )
        
        return EvaluationMetrics(
            ticker=ticker_data["ticker"],
            company_name=ticker_data["company_name"],
            sector=ticker_data["sector"],
            semantic_similarity=ticker_data["metrics"]["semantic_similarity"],
            ndcg_at_5=ticker_data["metrics"]["ndcg_at_5"],
            sector_specificity=ticker_data["metrics"]["sector_specificity"],
            source=ticker_data["source"]
        )
        
    except (KeyError, json.JSONDecodeError) as e:
        logger.error(f"Failed to get metrics for {ticker}: {e}")
        raise HTTPException(
            status_code=500,
            detail=f"Failed to retrieve metrics: {str(e)}"
        )


@router.get("/health")
async def evaluation_health() -> dict:
    """
    Check if evaluation system is healthy.
    
    Returns status of evaluation results and cache.
    """
    results_path = Path(__file__).parent.parent.parent.parent / "evaluation" / "results" / "evaluation_results.json"
    golden_outputs_path = Path(__file__).parent.parent.parent.parent / "evaluation" / "golden_outputs"
    
    results_exist = results_path.exists()
    cached_outputs = len(list(golden_outputs_path.glob("*.json"))) if golden_outputs_path.exists() else 0
    
    return {
        "status": "healthy" if results_exist else "no_results",
        "results_available": results_exist,
        "cached_outputs": cached_outputs,
        "results_path": str(results_path) if results_exist else None
    }
